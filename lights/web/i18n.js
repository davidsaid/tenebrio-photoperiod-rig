function detectLanguage() {
  try { const saved = localStorage.getItem("tenebrio-lang"); if (saved in STRINGS) return saved; } catch (err) { /* private mode */ }
  return (navigator.language || "es").toLowerCase().startsWith("es") ? "es" : "en";
}
const LANG = detectLanguage();

function t(key, vars = {}) {
  const text = STRINGS[LANG][key] ?? STRINGS.es[key] ?? key;
  return text.replace(/\{(\w+)\}/g, (_, name) => (name in vars ? vars[name] : `{${name}}`));
}

